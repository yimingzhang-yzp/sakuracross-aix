/**
 * 法定控除の定数表(年度ごとに見直しが必要なものをこのファイルに集約する)
 *
 * - 源泉所得税: 国税庁「源泉徴収税額表」の代わりに、財務省告示の
 *   「電子計算機等を使用して源泉徴収税額を計算する方法(電算機計算の特例)」の月額計算式を使う。
 *   甲欄(扶養控除等申告書の提出あり)のみが対象で、乙欄は 88,000 円未満の 3.063% ルールのみ実装する。
 * - 標準報酬月額: 健康保険(協会けんぽ)50 等級 / 厚生年金 32 等級の等級表。
 *
 * 保険料率(健保・介護・厚年・雇用)は都道府県・年度で変わるため、定数ではなく設定画面(settings)で持つ。
 *
 * 【年次更新】毎年 1 月(所得税)と 3 月(社会保険料率)に国税庁・協会けんぽの公表値と照合すること。
 */

/**
 * 金額の帯 [上限, 値] を並べた階段表。上限 Infinity で終端。
 * 上限を「含む」か「未満」かは表ごとに決める(等級表は未満、基礎控除は含む)。
 */
export type StepTable = ReadonlyArray<readonly [upperInclusive: number, value: number]>;

/** 「上限までは A × rate + offset」の区分線形表 */
export type LinearTable = ReadonlyArray<readonly [upperInclusive: number, rate: number, offset: number]>;

export interface IncomeTaxMonthlyTable {
  /** 表の呼称(明細のスナップショット用) */
  label: string;
  /** 給与所得控除の月額。A = 社会保険料等控除後の給与等の金額 */
  employmentIncomeDeduction: LinearTable;
  /** 基礎控除の月額(A の帯ごと) */
  basicDeduction: StepTable;
  /** 扶養親族等 1 人あたりの控除月額 */
  dependentDeductionPerPerson: number;
  /** 課税給与所得金額 B に対する税額(復興特別所得税込み)。value = B × rate + offset(offset は負) */
  tax: LinearTable;
}

